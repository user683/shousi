'''
给你一个整数数组 prices ，其中 prices[i] 表示某支股票第 i 天的价格。

在每一天，你可以决定是否购买和/或出售股票。你在任何时候 最多 只能持有 一股 股票。然而，你可以在 同一天 多次买卖该股票，但要确保你持有的股票不超过一股。

返回 你能获得的 最大 利润 。
'''

from typing import List

# ============================================================
# 解法一：贪心
# ============================================================
# 核心思路：
# 不限交易次数 + 同一天可以多次买卖 => 所有上涨的差价都能吃到
# 只要 prices[i] > prices[i-1]，就把差价累加到利润中
#
# 时间复杂度：O(n)
# 空间复杂度：O(1)
# ============================================================
class Solution:
    def maxProfit(self, prices: List[int]) -> int:
        profit = 0
        for i in range(1, len(prices)):
            if prices[i] > prices[i - 1]:
                profit += prices[i] - prices[i - 1]
        return profit


# ============================================================
# 解法二：DP（更通用，便于理解买卖股票系列问题）
# ============================================================
# dp[i][0]：第 i 天结束后【不持有】股票的最大利润
# dp[i][1]：第 i 天结束后【持有】股票的最大利润
#
# 状态转移：
#   dp[i][0] = max(dp[i-1][0], dp[i-1][1] + prices[i])  # 前一天也不持有 / 今天卖出
#   dp[i][1] = max(dp[i-1][1], dp[i-1][0] - prices[i])  # 前一天也持有 / 今天买入
#
# 因为本题不限交易次数，dp[i-1][0] 可以多次买入，所以买入时用 dp[i-1][0] 而非 -prices[i]
# 最终答案：dp[n-1][0]（最后一天不持有股票）
#
# 时间复杂度：O(n)
# 空间复杂度：O(n) / 可优化到 O(1)
# ============================================================
class SolutionDP:
    def maxProfit(self, prices: List[int]) -> int:
        n = len(prices)
        # dp[i][0]: 不持有, dp[i][1]: 持有
        dp = [[0, 0] for _ in range(n)]
        dp[0][0] = 0            # 第 0 天不持有：没买
        dp[0][1] = -prices[0]   # 第 0 天持有：买入

        for i in range(1, n):
            dp[i][0] = max(dp[i-1][0], dp[i-1][1] + prices[i])
            dp[i][1] = max(dp[i-1][1], dp[i-1][0] - prices[i])

        return dp[n-1][0]


# ============================================================
# 解法三：DP 空间优化版
# ============================================================
class SolutionDPOpt:
    def maxProfit(self, prices: List[int]) -> int:
        hold = -prices[0]   # 第0天买入，利润0-prices[0]
        cash = 0            # 不持有股票（现金）第0天什么都不做，利润=0

        for i in range(1, len(prices)):
            cash = max(cash, hold + prices[i]) # 卖出或不动
            hold = max(hold, cash - prices[i]) # 买入或不动

        return cash


